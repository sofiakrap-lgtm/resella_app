const dictionaries: Record<Language, Record<StringKey, string>> = { fi, en };

export function translate(
  language: Language,
  key: StringKey,
  params?: Record<string, string | number>,
): string {
  let value: string = dictionaries[language][key] ?? fi[key] ?? key;
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replace(`{${name}}`, String(replacement));
    }
  }
  return value;
}
