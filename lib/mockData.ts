/** Products added today, used by the "Uutta tänään" rows. */
export const newToday = (marketId?: string): Product[] =>
  products.filter(
    (p) => p.addedDaysAgo === 0 && p.status !== 'sold' && (!marketId || p.marketId === marketId),
  );

export function addedLabel(daysAgo: number): string {
  if (daysAgo === 0) return 'Tänään';
  if (daysAgo === 1) return 'Eilen';
  return `${daysAgo} päivää sitten`;
}

export function formatPrice(price: number): string {
  return `${price.toFixed(2).replace('.', ',')} €`;
}

/** Simple market level counter used when ranking markets by assortment. */
export function categoryCount(marketId: string, category: Category): number {
  return products.filter(
    (p) => p.marketId === marketId && p.category === category && p.status !== 'sold',
  ).length;
}
