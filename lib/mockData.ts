interface ProductInput extends Omit<Product, 'photos' | 'status' | 'sustainabilityNote' | 'keywords'> {
  status?: ProductStatus;
  sustainabilityNote?: string;
  keywords?: string[];
}

const NOTES: Record<Category, string> = {
  Vaatteet: 'Käytetty vaate säästää noin 10 kg hiilidioksidipäästöjä uuteen verrattuna.',
  Lastentarvikkeet: 'Lasten vaate ehtii palvella montaa perhettä, ennen kuin se on loppuun käytetty.',
  Astiat: 'Astiat kestävät sukupolvia, second hand on niille luonnollisin kierto.',
  Sisustus: 'Sisustustavara saa uuden kodin sen sijaan, että se päätyisi varastoon.',
  Vintage: 'Vintagelöytö on kierrätystä ja tyylivalinta samassa.',
  Jalkineet: 'Hyväkuntoiset kengät ansaitsevat toisen kierroksen.',
  Urheilu: 'Urheiluvälineet seisovat usein käyttämättöminä, kierrätys pitää ne liikkeessä.',
  Kirjat: 'Kirja on valmis luettavaksi uudelleen, sellaisenaan.',
};

function product(input: ProductInput): Product {
  return {
    ...input,
    status: input.status ?? 'available',
    sustainabilityNote: input.sustainabilityNote ?? NOTES[input.category],
    keywords: input.keywords ?? [],
    photos: [1, 2, 3].map((n) =>
      n === 1 ? `product-photos/${input.id}` : `product-photos/${input.id}-${n}`,
    ),
  };
}

